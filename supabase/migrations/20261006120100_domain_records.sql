/* ——— Access: members read their workspace; only the writer role writes ——— */

do $$
declare
  t text;
begin
  foreach t in array array[
    'companies', 'people', 'opportunities', 'opportunity_people', 'interactions',
    'drafts', 'next_actions', 'source_facts', 'interpretations', 'interpretation_facts'
  ]
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format(
      'create policy "Members can read their workspace''s records" on public.%I '
      'for select to authenticated, reachout_writer '
      'using (workspace_id in (select private.member_workspaces()))',
      t
    );
    execute format(
      'create policy "Writes stay inside the member''s workspace" on public.%I '
      'for all to reachout_writer '
      'using (workspace_id in (select private.member_workspaces())) '
      'with check (workspace_id in (select private.member_workspaces()))',
      t
    );
    execute format('revoke all on public.%I from public, anon, authenticated', t);
    execute format('grant select on public.%I to authenticated', t);
    execute format('grant select, insert, update, delete on public.%I to reachout_writer', t);
  end loop;
end
$$;
